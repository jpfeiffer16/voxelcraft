#!/usr/bin/env python3
"""Convert assets.json (exported from the web build by export_assets.js) into Palm resources.

Outputs (palm/res/):
  tiles0.bin / tiles1.bin  16x16 block tiles 0..63 / 64..127, RGB565 little-endian, 0xF81F = transparent
  spr_<type>.bin           4 views x 40x40 mob sprites, same pixel format
  icon*.bmp                launcher icons (isometric grass block, like the web favicon)
and palm/src/core/font.h   8x16 ASCII glyphs rendered from GNU Unifont (OFL/GPL w/ font exception)
"""
import json, os, sys
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.dirname(os.path.abspath(__file__))
PALM = os.path.dirname(HERE)
RES = os.path.join(PALM, 'res')
os.makedirs(RES, exist_ok=True)
d = json.load(open(os.path.join(HERE, 'assets.json')))
KEY = 0xF81F
def rgb565(r, g, b, a):
    if a < 128: return KEY
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return 0xF81E if v == KEY else v
def pack(px):
    out = bytearray()
    for i in range(0, len(px), 4):
        v = rgb565(*px[i:i + 4]); out += bytes((v & 255, v >> 8))
    return out
tiles = {int(k): v for k, v in d['tiles'].items()}
for part in (0, 1):
    buf = bytearray()
    for i in range(part * 64, part * 64 + 64):
        buf += pack(tiles[i]) if i in tiles else bytes(512)
    open(os.path.join(RES, 'tiles%d.bin' % part), 'wb').write(buf)
for t, views in d['sprites'].items():
    buf = bytearray()
    for v in views: buf += pack(v)
    open(os.path.join(RES, 'spr_%s.bin' % t), 'wb').write(buf)

# ---- font
fp = '/usr/share/fonts/opentype/unifont/unifont.otf'
if not os.path.exists(fp):
    import glob; fp = (glob.glob('/usr/share/fonts/**/unifont*.otf', recursive=True) + glob.glob('/usr/share/fonts/**/unifont*.ttf', recursive=True))[0]
font = ImageFont.truetype(fp, 16)
rows = []
for c in range(32, 127):
    im = Image.new('L', (8, 16), 0); ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
    bs = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 127: b |= 0x80 >> x
        bs.append(b)
    rows.append(bs)
with open(os.path.join(PALM, 'src', 'core', 'font.h'), 'w') as f:
    f.write('/* 8x16 ASCII 32..126 from GNU Unifont (generated by tools/mkassets.py) */\n')
    f.write('static const unsigned char FONT8x16[95][16] = {\n')
    for c, bs in zip(range(32, 127), rows):
        f.write('  {' + ','.join('0x%02x' % b for b in bs) + '}, /* %r */\n' % chr(c))
    f.write('};\n')

# ---- launcher icons: isometric grass block from the real tiles
def tile_img(i):
    return Image.frombytes('RGBA', (16, 16), bytes(tiles[i]))
def iso_block(size):
    top, side = tile_img(0), tile_img(1)
    S = 64; im = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    # affine-map tiles onto three faces (like textures.drawIcon)
    s = S / 2; k = s / 16.0
    def face(src, quad, shade):
        src = src.convert('RGBA')
        px = src.load()
        dr = im.load()
        (ox, oy), (ux, uy), (vx, vy) = quad
        for y in range(16 * 8):
            for x in range(16 * 8):
                u, v = x / 8.0, y / 8.0
                X = int(ox + ux * u + vx * v); Y = int(oy + uy * u + vy * v)
                if 0 <= X < S and 0 <= Y < S:
                    r, g, b, a = px[int(u), int(v)]
                    if a > 128: dr[X, Y] = (int(r * shade), int(g * shade), int(b * shade), 255)
    cx, top0 = S / 2, 2
    face(top, ((cx, top0), (k, k * 0.5), (-k, k * 0.5)), 1.0)
    face(side, ((cx - s, top0 + s * 0.5), (k, k * 0.5), (0, k)), 0.8)
    face(side, ((cx, top0 + s), (k, -k * 0.5), (0, k)), 0.65)
    return im
blk = iso_block(64)
def save_bmp(img, w, h, name, bg=(255, 255, 255)):
    c = Image.new('RGB', (w, h), bg)
    b = img.resize((min(w, h), min(w, h)), Image.LANCZOS)
    c.paste(b, ((w - b.width) // 2, (h - b.height) // 2), b)
    c.save(os.path.join(RES, name))
save_bmp(blk, 32, 32, 'icon_large.bmp'); save_bmp(blk, 64, 64, 'icon_large_hd.bmp')
save_bmp(blk, 15, 9, 'icon_small.bmp'); save_bmp(blk, 30, 18, 'icon_small_hd.bmp')
blk.resize((128, 128), Image.NEAREST).save(os.path.join(RES, 'icon_preview.png'))
print('ok: tiles', len(tiles), 'sprites', list(d['sprites']))
